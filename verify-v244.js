const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('member-password-import.js','utf8');
const leader=fs.readFileSync('leader-center.js','utf8');
const app=fs.readFileSync('app.js','utf8');
const cloud=fs.readFileSync('firebase-cloud.js','utf8');
const context={window:{}};
vm.runInNewContext(source,context);
const cache=context.window.memberPasswordSession;
assert(cache,'session password cache must be available to save and export flows');
assert.strictEqual(cache.get('Quality','member-1'),'','unsaved passwords must stay blank');
cache.remember('quality','member-1','newSecret123');
assert.strictEqual(cache.get('QUALITY','member-1'),'newSecret123','saved passwords must be retrievable across department-key casing');
assert.strictEqual(cache.get('quality','member-2'),'','passwords must not leak between accounts');
assert(!source.includes('localStorage')&&!source.includes('sessionStorage'),'plaintext password cache must not use persistent browser storage');
assert(leader.includes("window.memberPasswordSession?.get(dept.key,r.id)"),'Excel rows must read the per-member session password');
assert(leader.includes('${excelCell(r.password)}')&&leader.includes('${esc(r.password)}</td>'),'Excel download and preview must show saved session passwords');
assert(cloud.includes('window.memberPasswordSession?.remember(k,confirmed.id,password)'),'department password must be remembered only after server confirmation');
assert(app.includes("window.memberPasswordSession?.remember('rnd',confirmed.id,password)"),'R&D password must be remembered after verified save');
console.log('PASS v244: Firebase-confirmed per-member passwords appear in preview/export using memory-only storage.');
