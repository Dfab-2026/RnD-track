 assert.equal(rows[0].type,'kpi_target_standard');
 adminActive=false;
 await assert.rejects(api.saveStandard('quality','ISO Process Implementation','Changed'),/administrator/);
 assert.equal(calls,1);
 adminActive=true;
 await assert.rejects(api.saveStandard('quality','ISO Process Implementation',''),/between 1 and 500/);
 assert.equal(calls,1);
 const denied={...cloud,saveDepartmentRecord:async()=>{throw Error('permission-denied')}};
 context.window.rndCloud=denied;
 await assert.rejects(api.saveStandard('quality','ISO Process Implementation','Another target'),/permission-denied/);
 console.log('PASS v299: standard edit stored with canonical KPI identity, Firebase read-back, admin-only access, validation, denied writes and department integration');
