$ErrorActionPreference = "Stop"
$ProjectId = "dfab-rnd-track"
Set-Location $PSScriptRoot

function Run-Firebase([string[]]$Args) {
  $out = & npx.cmd firebase-tools @Args 2>&1 | Out-String
  if ($LASTEXITCODE -ne 0) { throw $out.Trim() }
  return $out
}

Write-Host ""
Write-Host "R&D TRACK - Firebase setup" -ForegroundColor Cyan
Write-Host "Project: $ProjectId"
Write-Host ""

try {
  Run-Firebase @("projects:list","--json") | Out-Null
} catch {
  Write-Host "Firebase login is required. Opening login..." -ForegroundColor Yellow
  & npx.cmd firebase-tools login
  if ($LASTEXITCODE -ne 0) { throw "Firebase login failed." }
}

Write-Host "Finding Firebase Web App..." -ForegroundColor Cyan
$apps = Run-Firebase @("apps:list","WEB","--project",$ProjectId,"--json")
$appId = [regex]::Match($apps, '1:\d+:web:[A-Za-z0-9]+').Value

if (-not $appId) {
  Write-Host "No Web App found. Creating one..." -ForegroundColor Yellow
  $created = Run-Firebase @("apps:create","WEB","R&D Track Web","--project",$ProjectId,"--json")
  $appId = [regex]::Match($created, '1:\d+:web:[A-Za-z0-9]+').Value
}
if (-not $appId) { throw "Could not find or create a Firebase Web App for $ProjectId." }

Write-Host "Web App: $appId" -ForegroundColor Green
$sdk = Run-Firebase @("apps:sdkconfig","WEB",$appId,"--project",$ProjectId)
$jsonMatch = [regex]::Match($sdk, '\{[\s\S]*\}')
if (-not $jsonMatch.Success) { throw "Firebase CLI returned no Web SDK config." }

$configObj = $jsonMatch.Value | ConvertFrom-Json
if (-not $configObj.apiKey -or -not $configObj.projectId -or -not $configObj.appId) {
  throw "Firebase SDK config is incomplete."
}

$json = $configObj | ConvertTo-Json -Depth 10
$content = @"
// Auto-generated by SETUP-FIREBASE.ps1 for $ProjectId.
// Firebase Web config is public client configuration; Firestore rules protect the data.
window.RND_FIREBASE_CONFIG = $json;
try { localStorage.setItem('rnd_firebase_config', JSON.stringify(window.RND_FIREBASE_CONFIG)); } catch(e) {}
"@
Set-Content -Path (Join-Path $PSScriptRoot "firebase-config.js") -Value $content -Encoding UTF8

Write-Host ""
Write-Host "Firebase config written successfully." -ForegroundColor Green
Write-Host "Deploying Firestore rules..." -ForegroundColor Cyan
& npx.cmd firebase-tools deploy --only firestore:rules --project $ProjectId
if ($LASTEXITCODE -ne 0) { throw "Config is fixed, but Firestore rules deployment failed." }

Write-Host ""
Write-Host "DONE - Firebase config + Firestore rules are ready." -ForegroundColor Green
Write-Host "Now hard-refresh the website (Ctrl+Shift+R)." -ForegroundColor Yellow
